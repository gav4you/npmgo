// Package server is a Go translation of the server renderer of the npm
// package react-dom@19.2.4 (https://github.com/facebook/react,
// packages/react-dom; behaviour taken from the production builds
// cjs/react-dom-server-legacy.node.production.js and
// cjs/react-dom-server.node.production.js, i.e. React's "Fizz" renderer).
// The original copyright notice and MIT license are preserved in LICENSE.
//
// # API
//
// RenderToString and RenderToStaticMarkup render a tree synchronously, like
// their JavaScript namesakes: a component that suspends inside a Suspense
// boundary shows the fallback (client-rendered boundary), one that suspends
// outside any boundary is an error, and thrown errors are returned.
//
// RenderToPipeableStream starts a streaming render and returns a
// PipeableStream. Pipe(w) streams the HTML to w (shell first, then each
// completed Suspense boundary with its inline script) and returns when the
// stream has ended; Abort stops waiting. The StreamOptions callbacks
// (OnShellReady, OnShellError, OnAllReady, OnError) are called on the
// goroutine running Pipe or Wait, in the order Node calls them; Pipe may be
// called from OnShellReady / OnAllReady (after Wait), as in Node.
//
// Components, elements and hooks are those of package react; see its doc.
// Rendering keeps all state per request, so concurrent renders on different
// goroutines are independent.
//
// # Event loop
//
// The streaming renderer schedules work exactly as in Node (performWork in a
// microtask, retries and flushes with setImmediate). Each stream runs a
// small event loop (see internal/jsloop) on the goroutine driving it;
// promises settled on other goroutines queue their reactions onto it.
// RenderToString runs as one event-loop task: promise reactions queued while
// it rendered run before it returns (so a promise React tracked during one
// call is seen as settled by the next).
//
// Not ported: the prerender / resume APIs (prerender, prerenderToNodeStream,
// resume, resumeAndPrerender, resumeToPipeableStream) and their replay and
// postpone machinery, renderToReadableStream (web streams), Node stream
// backpressure ('drain'), unstable_externalRuntimeSrc, development-only
// warnings, and V8 source locations in component stacks.
package server

import (
	"fmt"
	"io"
	"os"
	"strings"

	"github.com/gav4you/npmgo/internal/jsvalue"
	"github.com/gav4you/npmgo/pkgs/react"
)

// Version is the react-dom version this package translates.
const Version = "19.2.4"

// Options are the options of RenderToString and RenderToStaticMarkup.
type Options struct {
	// IdentifierPrefix prefixes the ids generated by Hooks.UseId.
	IdentifierPrefix string
}

func newError(msg string) *react.Error { return &react.Error{Message: msg} }

// ToError converts a thrown JavaScript value into a Go error: errors are
// returned as they are, other values wrapped in *react.Panic.
func ToError(v any) error {
	if e, ok := v.(error); ok && e != nil {
		return e
	}
	return &react.Panic{Value: v}
}

// ConsoleError is what the streaming renderer's default onError does with an
// error (Node: console.error). Replace it to redirect.
var ConsoleError = func(err any) { fmt.Fprintln(os.Stderr, err) }

type stringDestination struct {
	b          strings.Builder
	didFatal   bool
	fatalError any
}

func (d *stringDestination) write(chunk string) bool { d.b.WriteString(chunk); return true }
func (d *stringDestination) beginWriting()           {}
func (d *stringDestination) completeWriting()        {}
func (d *stringDestination) flushBuffered()          {}
func (d *stringDestination) end()                    {}
func (d *stringDestination) destroy(err any) {
	d.didFatal = true
	d.fatalError = err
}

const (
	renderToStringAbortReason       = "The server used \"renderToString\" which does not support Suspense. If you intended for this Suspense boundary to render the fallback content on the server consider throwing an Error somewhere within the Suspense boundary. If you intended to have the server wait for the suspended component please switch to \"renderToPipeableStream\" which supports Suspense on the server"
	renderToStaticMarkupAbortReason = "The server used \"renderToStaticMarkup\" which does not support Suspense. If you intended to have the server wait for the suspended component please switch to \"renderToPipeableStream\" which supports Suspense on the server"
	suspendedSynchronouslyMessage   = "A component suspended while responding to synchronous input. This will cause the UI to be replaced with a loading indicator. To fix, updates that suspend should be wrapped with startTransition."
)

func renderToStringImpl(children any, options *Options, generateStaticMarkup bool, abortReason string) (html string, err error) {
	var identifierPrefix any = jsvalue.Undefined{}
	if options != nil {
		identifierPrefix = options.IdentifierPrefix
	}
	rs := createResumableState(identifierPrefix, jsvalue.Undefined{}, jsvalue.Undefined{}, jsvalue.Undefined{})
	readyToStream := false
	r := newRequest(legacyFlavor, children, rs, createLegacyRenderState(rs, generateStaticMarkup), createFormatContext(rootHTMLMode, nil, 0), infinity,
		func(any, *ErrorInfo) any { return nil }, nil, func() { readyToStream = true }, nil, nil, nil)
	dest := &stringDestination{}
	thrown, panicked := try(func() {
		r.flushScheduled = r.destination != nil
		r.performWork()
		if r.status == statusOpening {
			r.status = statusOpen
		}
		r.safelyEmitEarlyPreloads(r.pendingRootTasks == 0)
		r.abort(abortReason)
		r.startFlowing(dest)
	})
	r.loop.Close()
	if panicked {
		return "", ToError(react.Thrown(thrown))
	}
	if dest.didFatal && !jsvalue.StrictEquals(dest.fatalError, abortReason) {
		return "", ToError(dest.fatalError)
	}
	if !readyToStream {
		return "", newError(suspendedSynchronouslyMessage)
	}
	return dest.b.String(), nil
}

// RenderToString is ReactDOMServer.renderToString(children, options).
func RenderToString(children react.Node, options ...*Options) (string, error) {
	return renderToStringImpl(children, firstOptions(options), false, renderToStringAbortReason)
}

// RenderToStaticMarkup is ReactDOMServer.renderToStaticMarkup(children,
// options): like RenderToString without the text separators and Suspense
// markers React needs for hydration.
func RenderToStaticMarkup(children react.Node, options ...*Options) (string, error) {
	return renderToStringImpl(children, firstOptions(options), true, renderToStaticMarkupAbortReason)
}

func firstOptions(o []*Options) *Options {
	if len(o) > 0 {
		return o[0]
	}
	return nil
}

// StreamOptions are the options of RenderToPipeableStream. Fields left at
// their zero value are "not passed".
type StreamOptions struct {
	IdentifierPrefix string
	// NamespaceURI starts rendering inside <svg> or <math> content.
	NamespaceURI string
	// Nonce is a string, or an *react.Object {script, style}.
	Nonce any
	// BootstrapScriptContent is inline script content (any value; nil is
	// not passed).
	BootstrapScriptContent any
	// BootstrapScripts and BootstrapModules list strings or *react.Object
	// {src, integrity, crossOrigin}.
	BootstrapScripts []any
	BootstrapModules []any
	// ImportMap is an object rendered as <script type="importmap">.
	ImportMap any
	// ProgressiveChunkSize (bytes) controls when completed boundaries are
	// streamed separately; 0 means React's default (12800).
	ProgressiveChunkSize int
	// OnHeaders receives the early Link header; MaxHeadersLength (default
	// 2000) caps it.
	OnHeaders        func(headers map[string]string)
	MaxHeadersLength int
	// FormState is the postback state for useActionState
	// ([state, key, referenceId, boundArgs]); nil is not passed.
	FormState any
	// OnShellReady, OnShellError, OnAllReady and OnError are React's
	// callbacks. OnError returns the error digest ("" for none); when nil
	// errors are printed with ConsoleError.
	OnShellReady func()
	OnShellError func(err error)
	OnAllReady   func()
	OnError      func(err error, info ErrorInfo) string
}

// PipeableStream is what RenderToPipeableStream returns.
type PipeableStream struct {
	r                 *request
	hasStartedFlowing bool
	driving           bool
	dest              *writerDestination
	writeErrHandled   bool
}

// RenderToPipeableStream is ReactDOMServer.renderToPipeableStream(children,
// options). Rendering starts when the stream is driven by Pipe or Wait.
func RenderToPipeableStream(children react.Node, opts *StreamOptions) *PipeableStream {
	if opts == nil {
		opts = &StreamOptions{}
	}
	var identifierPrefix any = jsvalue.Undefined{}
	if opts.IdentifierPrefix != "" {
		identifierPrefix = opts.IdentifierPrefix
	}
	var bootstrapScriptContent, bootstrapScripts, bootstrapModules any = jsvalue.Undefined{}, jsvalue.Undefined{}, jsvalue.Undefined{}
	if opts.BootstrapScriptContent != nil {
		bootstrapScriptContent = opts.BootstrapScriptContent
	}
	if opts.BootstrapScripts != nil {
		bootstrapScripts = opts.BootstrapScripts
	}
	if opts.BootstrapModules != nil {
		bootstrapModules = opts.BootstrapModules
	}
	rs := createResumableState(identifierPrefix, bootstrapScriptContent, bootstrapScripts, bootstrapModules)
	var nonce, importMap, maxHeadersLength any = jsvalue.Undefined{}, jsvalue.Undefined{}, jsvalue.Undefined{}
	if opts.Nonce != nil {
		nonce = opts.Nonce
	}
	if opts.ImportMap != nil {
		importMap = opts.ImportMap
	}
	if opts.MaxHeadersLength != 0 {
		maxHeadersLength = opts.MaxHeadersLength
	}
	st := createRenderState(rs, nonce, importMap, opts.OnHeaders, maxHeadersLength, false)
	var namespaceURI any = jsvalue.Undefined{}
	if opts.NamespaceURI != "" {
		namespaceURI = opts.NamespaceURI
	}
	chunkSize := 12800.0
	if opts.ProgressiveChunkSize != 0 {
		chunkSize = float64(opts.ProgressiveChunkSize)
	}
	var onError func(any, *ErrorInfo) any
	if opts.OnError != nil {
		f := opts.OnError
		onError = func(err any, info *ErrorInfo) any {
			if d := f(ToError(err), *info); d != "" {
				return d
			}
			return nil
		}
	}
	var onShellError func(any)
	if opts.OnShellError != nil {
		f := opts.OnShellError
		onShellError = func(err any) { f(ToError(err)) }
	}
	r := newRequest(streamFlavor, children, rs, st, createRootFormatContext(namespaceURI), chunkSize,
		onError, opts.OnAllReady, opts.OnShellReady, onShellError, nil, opts.FormState)
	// startWork
	r.flushScheduled = r.destination != nil
	r.loop.QueueMicrotask(r.performWork)
	r.loop.SetImmediate(func() {
		if r.status == statusOpening {
			r.status = statusOpen
		}
		r.safelyEmitEarlyPreloads(r.pendingRootTasks == 0)
	})
	return &PipeableStream{r: r}
}

// Pipe starts streaming the HTML to w. Called from a stream callback (for
// example OnShellReady during Wait) it only attaches w and returns, as in
// Node. Otherwise it then drives the render on the calling goroutine and
// returns when the stream has ended: nil, the error the render was destroyed
// with, or the first error writing to w. If w has a Flush method it is
// called after each batch of writes. Pipe may be called once.
func (s *PipeableStream) Pipe(w io.Writer) error {
	d := &writerDestination{w: w}
	if err := s.attach(d); err != nil {
		return err
	}
	s.dest = d
	if s.driving {
		return nil
	}
	return s.drive()
}

// attach is the JavaScript pipe(destination) minus the event handlers.
func (s *PipeableStream) attach(d destination) error {
	if s.hasStartedFlowing {
		return newError("React currently only supports piping to one writable stream.")
	}
	s.hasStartedFlowing = true
	r := s.r
	r.safelyEmitEarlyPreloads(r.pendingRootTasks == 0)
	r.startFlowing(d)
	return nil
}

// Wait drives the render on the calling goroutine until the stream has
// ended, or, if it was never piped, until all work is done or the shell
// failed. It returns the fatal error, if any.
func (s *PipeableStream) Wait() error { return s.drive() }

// Abort aborts the render with reason (nil means no reason). It is safe to
// call from any goroutine; it takes effect on the goroutine driving the
// stream (if called from one of the stream's callbacks, after the current
// task).
func (s *PipeableStream) Abort(reason any) {
	if reason == nil {
		reason = jsvalue.Undefined{}
	}
	r := s.r
	r.loop.SetImmediate(func() { r.abort(reason) })
}

func (s *PipeableStream) done() bool {
	r := s.r
	if d := s.dest; d != nil {
		if d.err != nil && !s.writeErrHandled {
			s.writeErrHandled = true
			r.loop.SetImmediate(func() {
				r.destination = nil
				r.abort(newError("The destination stream errored while writing data."))
			})
			return false
		}
		if d.ended || d.destroyed {
			return true
		}
		if d.err != nil && r.destination == nil && r.allPendingTasks == 0 {
			return true
		}
		return false
	}
	return r.status == statusClosing || r.status == statusClosed || r.allPendingTasks == 0
}

func (s *PipeableStream) drive() error {
	s.driving = true
	s.r.loop.Run(s.done)
	s.driving = false
	r := s.r
	if r.status == statusClosed {
		r.loop.Close()
	}
	if d := s.dest; d != nil {
		if d.err != nil {
			return d.err
		}
		if d.destroyed {
			return ToError(d.destroyErr)
		}
		return nil
	}
	if r.status == statusClosing {
		return ToError(r.fatalError)
	}
	return nil
}

// writerDestination adapts an io.Writer to React's Writable destination,
// buffering writes the way React's writeChunk does.
type writerDestination struct {
	w          io.Writer
	buf        []byte
	err        error
	ended      bool
	destroyed  bool
	destroyErr any
}

const viewSize = 2048

func (d *writerDestination) flushBuf() {
	if len(d.buf) == 0 {
		return
	}
	if d.err == nil {
		_, d.err = d.w.Write(d.buf)
	}
	d.buf = d.buf[:0]
}

func (d *writerDestination) write(chunk string) bool {
	if len(chunk) == 0 {
		return true
	}
	if len(chunk) > viewSize {
		d.flushBuf()
		if d.err == nil {
			_, d.err = io.WriteString(d.w, chunk)
		}
		return true
	}
	if len(d.buf)+len(chunk) > viewSize {
		d.flushBuf()
	}
	d.buf = append(d.buf, chunk...)
	if len(d.buf) == viewSize {
		d.flushBuf()
	}
	return true
}

func (d *writerDestination) beginWriting()    {}
func (d *writerDestination) completeWriting() { d.flushBuf() }
func (d *writerDestination) flushBuffered() {
	switch f := d.w.(type) {
	case interface{ Flush() error }:
		if err := f.Flush(); err != nil && d.err == nil {
			d.err = err
		}
	case interface{ Flush() }:
		f.Flush()
	}
}
func (d *writerDestination) end() { d.ended = true }
func (d *writerDestination) destroy(err any) {
	d.destroyed = true
	d.destroyErr = err
}
