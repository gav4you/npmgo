// Generates internal/nodeutil/width_table.go from Node's real ICU-backed
// getStringWidth (one code point at a time, control chars kept).
// Run: node --expose-internals tools/gen_width_table.cjs > internal/nodeutil/width_table.go
'use strict';
const { getStringWidth } = require('internal/util/inspect');
const ranges = []; // [start, end, width] for width != 1
let cur = null;
for (let cp = 0x80; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue; // lone surrogates: not representable in Go strings
  const w = getStringWidth(String.fromCodePoint(cp), false);
  if (w === 1) { cur = null; continue; }
  if (cur && cur[2] === w && cur[1] === cp - 1) cur[1] = cp;
  else { cur = [cp, cp, w]; ranges.push(cur); }
}
let out = `// Code generated by tools/gen_width_table.cjs from Node ${process.version} ` +
  `(ICU ${process.versions.icu}, Unicode ${process.versions.unicode}). DO NOT EDIT.\n\n` +
  `package nodeutil\n\n// icuWidthRanges lists code points >= 0x80 whose ICU column width is not 1.\n` +
  `var icuWidthRanges = [...]struct {\n\tlo, hi rune\n\tw      uint8\n}{\n`;
for (const [a, b, w] of ranges) out += `\t{0x${a.toString(16)}, 0x${b.toString(16)}, ${w}},\n`;
out += '}\n';
process.stdout.write(out);
console.error(ranges.length + ' ranges');
