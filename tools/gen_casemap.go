//go:build ignore

// Generates internal/jsvalue/casemap_supplement.go from parity/jsvalue/casemap.json (every case mapping of Node's
// ICU that is not the identity, recorded by tools/gen_casemap.cjs): the mappings golang.org/x/text's tables lack,
// which jsvalue.ToUpperCase and ToLowerCase apply before x/text's. Only simple mappings (one code point to one code
// point) can be supplemented; the generator refuses any other difference, and any mapping x/text has that Node
// does not.
//
// Run: go run tools/gen_casemap.go parity/jsvalue/casemap.json internal/jsvalue/casemap_supplement.go
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"strings"
	"unicode"

	"golang.org/x/text/cases"
	"golang.org/x/text/language"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: go run tools/gen_casemap.go <casemap.json> <casemap_supplement.go>")
		os.Exit(2)
	}
	raw, err := os.ReadFile(os.Args[1])
	check(err)
	var rec struct {
		Node, ICU, Unicode string
		Mappings           [][3]json.RawMessage
	}
	check(json.Unmarshal(raw, &rec))
	upper, lower := cases.Upper(language.Und), cases.Lower(language.Und)
	type pair struct{ from, to rune }
	var ups, lows []pair
	recorded := map[rune]bool{}
	for _, m := range rec.Mappings {
		var cp rune
		check(json.Unmarshal(m[0], &cp))
		recorded[cp] = true
		ch := string(cp)
		for i, c := range []struct {
			caser cases.Caser
			name  string
			to    *[]pair
		}{{upper, "upper", &ups}, {lower, "lower", &lows}} {
			want := ch
			if string(m[i+1]) != "null" {
				var out []rune
				check(json.Unmarshal(m[i+1], &out))
				want = string(out)
			}
			got := c.caser.String(ch)
			if got == want {
				continue
			}
			if got != ch || len([]rune(want)) != 1 {
				fail("U+%04X %s: Node %q, x/text %q: not a simple mapping x/text lacks", cp, c.name, want, got)
			}
			*c.to = append(*c.to, pair{cp, []rune(want)[0]})
		}
	}
	for cp := rune(0); cp <= unicode.MaxRune; cp++ {
		if cp >= 0xD800 && cp <= 0xDFFF || recorded[cp] {
			continue
		}
		if ch := string(cp); upper.String(ch) != ch || lower.String(ch) != ch {
			fail("U+%04X: x/text maps it, Node does not", cp)
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/gen_casemap.go from parity/jsvalue/casemap.json (Node %s, ICU %s, Unicode %s) against\n"+
		"// golang.org/x/text/cases (Unicode %s); DO NOT EDIT.\n\npackage jsvalue\n\n", rec.Node, rec.ICU, rec.Unicode, cases.UnicodeVersion)
	b.WriteString("// upperSupplement and lowerSupplement are the simple case mappings of Node's ICU that golang.org/x/text's tables\n" +
		"// lack (letters whose case pairs were added to Unicode after x/text's version); ToUpperCase and ToLowerCase apply\n" +
		"// them before x/text's mapping.\n")
	for _, t := range []struct {
		name  string
		pairs []pair
	}{{"upperSupplement", ups}, {"lowerSupplement", lows}} {
		fmt.Fprintf(&b, "var %s = map[rune]rune{\n", t.name)
		for _, p := range t.pairs {
			fmt.Fprintf(&b, "\t0x%04X: 0x%04X,\n", p.from, p.to)
		}
		b.WriteString("}\n\n")
	}
	src, err := format.Source([]byte(b.String()))
	check(err)
	check(os.WriteFile(os.Args[2], src, 0o644))
	fmt.Printf("%d upper and %d lower mappings supplemented\n", len(ups), len(lows))
}

func check(err error) {
	if err != nil {
		fail("%v", err)
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen_casemap: "+format+"\n", args...)
	os.Exit(1)
}
